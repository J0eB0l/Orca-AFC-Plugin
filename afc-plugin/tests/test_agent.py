class Calls:
    """What the agent told OrcaSlicer through its callbacks, in order."""

    def __init__(self):
        self.events = []
        self._cond = threading.Condition()

    def record(self, *event):
        with self._cond:
            self.events.append(event)
            self._cond.notify_all()

    def wait_for(self, test, count=1, timeout=10.0):
        deadline = time.monotonic() + timeout
        with self._cond:
            while True:
                found = [e for e in self.events if test(e)]
                if len(found) >= count:
                    return found
                left = deadline - time.monotonic()
                if left <= 0:
                    raise AssertionError("expected %d such events, got %r" % (count, self.events))
                self._cond.wait(left)

    def messages(self, key, command, count=1):
        found = self.wait_for(lambda e: e[0] == "message" and e[2].get(key, {}).get("command") == command, count)
        return [e[2][key] for e in found]


class Case(unittest.TestCase):
    poll = 3600.0  # no pushes but the ones a test asks for

    def setUp(self):
        self.fake = FakeMoonraker()
        self.addCleanup(self.fake.close)
        self.fake.webhook = webhook_fixture()
        self.fake.objects = {"AFC": {"multiple_tool_mapping": True},
                             "print_stats": {"state": "standby", "filename": "", "print_duration": 0},
                             "toolhead": {"homed_axes": "xy", "extruder": "extruder1"},
                             "extruder": {"temperature": 25.0, "target": 0.0},
                             "extruder1": {"temperature": 210.4, "target": 215.0},
                             "heater_bed": {"temperature": 59.8, "target": 60.0},
                             "fan": {"speed": 0.5}, "virtual_sdcard": {"progress": 0.0}}
        folder = tempfile.TemporaryDirectory()
        self.addCleanup(folder.cleanup)
        self.folder = folder.name
        orca.bundle = profiles(self.folder)
        self.addCleanup(setattr, orca, "bundle", PresetBundle())
        # AFC's newest versions, as GitHub has them.
        latest = mock.patch.object(afc_agent.upstream, "read", return_value={"main": "1.2.0", "DEV": "1.2.8"})
        latest.start()
        self.addCleanup(latest.stop)
        self.agent = AFCAgent(poll=self.poll)
        self.addCleanup(self.agent.on_unload)
        self.calls = calls = Calls()
        a = self.agent
        a.set_queue_on_main_fn(lambda fn: fn())  # the tests' UI thread is whichever thread queues
        a.set_on_ssdp_msg_fn(lambda msg: calls.record("ssdp", json.loads(msg)))
        a.set_on_local_connect_fn(lambda state, dev, msg: calls.record("local_connect", state, dev, msg))
        a.set_on_printer_connected_fn(lambda dev: calls.record("printer_connected", dev))
        a.set_on_local_message_fn(lambda dev, msg: calls.record("message", dev, json.loads(msg)))
        host, port = self.fake.url[len("http://"):].split(":")
        self.dev_id = "%s:%s" % (host, port)
        self.params = PrinterConnectionParams(dev_id=self.dev_id, host=host, port=port, password="88888888")

    def connect(self):
        self.assertEqual(self.agent.connect_printer(self.params), 0)
        self.calls.wait_for(lambda e: e[0] == "printer_connected")

    def send(self, payload):
        return self.agent.send_message_to_printer(self.dev_id, json.dumps(payload), 0, 0)

    def push(self, count=1):
        self.assertEqual(self.send({"pushing": {"command": "pushall"}}), 0)
        return self.calls.messages("print", "push_status", count)[-1]


class ConnectTest(Case):
    def test_announces_then_connects(self):
        self.connect()
        kinds = [e[0] for e in self.calls.events]
        self.assertEqual(kinds, ["ssdp", "local_connect", "printer_connected"])
        ssdp = self.calls.events[0][1]
        self.assertEqual((ssdp["dev_id"], ssdp["dev_ip"], ssdp["dev_name"], ssdp["dev_type"]),
                         (self.dev_id, self.dev_id, "voron", "Voron2_300"))
        self.assertEqual((ssdp["connect_type"], ssdp["bind_state"]), ("lan", "free"))
        self.assertEqual(self.calls.events[1][1:], (0, self.dev_id, "0"))

    def test_unknown_model_is_announced_as_none(self):
        # A model name never matches the preset's model_id, so OrcaSlicer's sync would refuse it.
        orca.bundle.printer.values["printer_model"] = "Nobody's Printer"
        self.connect()
        self.assertEqual(self.calls.events[0][1]["dev_type"], "")

