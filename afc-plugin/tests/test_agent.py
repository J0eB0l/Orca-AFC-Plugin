class PrintTest(Case):
    def project(self, text=PLATE, plate=1):
        path = os.path.join(self.folder, "plate_%d.3mf" % plate)
        with zipfile.ZipFile(path, "w") as z:
            z.writestr("3D/3dmodel.model", "<model/>")
            z.writestr("Metadata/plate_%d.gcode" % plate, text)
        return path

    def print_params(self, **values):
        defaults = dict(dev_id=self.dev_id, project_name="Cube box", plate_index=1,
                        ams_mapping="[4,0]",
                        ams_mapping2='[{"ams_id":1,"slot_id":0},{"ams_id":0,"slot_id":0}]')
        defaults.update(values)
        if "filename" not in defaults:  # a default project would overwrite the one passed in
            defaults["filename"] = self.project()
        return PrintParams(**defaults)

    def start(self, params, cancel=lambda: False):
        stages = []
        code = self.agent.start_local_print(params, lambda *stage: stages.append(stage), cancel)
        return code, stages

    def test_prints_on_the_dialogs_trays(self):
        self.connect()
        code, stages = self.start(self.print_params())
        self.assertEqual(code, 0)
        self.assertEqual(self.fake.started, ["Cube_box_plate_1.gcode"])
        text = self.fake.uploads["Cube_box_plate_1.gcode"].decode()
